import * as Print from 'expo-print';
import * as Sharing from 'expo-sharing';
import { Platform } from 'react-native';

export async function printSoapNote({ note, patient, facility }) {
  const facilityName = facility?.name || 'AfyaScribe Facility';
  const doctorName = note.createdBy
    ? `Dr. ${note.createdBy.firstName} ${note.createdBy.lastName}`
    : 'Attending Doctor';
  const patientName = patient
    ? `${patient.firstName} ${patient.lastName}`
    : 'Patient';
  const dateStr = new Date(note.createdAt || Date.now()).toLocaleDateString('en-KE', {
    day: '2-digit', month: 'long', year: 'numeric',
  });

  const sections = [
    { label: 'S — Symptoms & History',    value: note.symptoms },
    { label: 'O — Physical Examination',  value: note.physicalExamination },
    { label: 'Lab Investigations',         value: note.labInvestigations },
    { label: 'Imaging',                    value: note.imaging },
    { label: 'A — Diagnosis',              value: note.diagnosis },
    note.icd11Code && { label: 'ICD-11 Code', value: `${note.icd11Code} — ${note.icd11Description || ''}` },
    { label: 'P — Management Plan',        value: note.management },
  ].filter(s => s && s.value && s.value.trim());

  const sectionHtml = sections.map(s => `
    <div class="section">
      <div class="section-label">${s.label}</div>
      <div class="section-body">${s.value.replace(/\n/g, '<br>')}</div>
    </div>`).join('');

  const html = `
<!DOCTYPE html>
<html>
<head><meta charset="utf-8"><style>
  * { margin:0; padding:0; box-sizing:border-box; }
  body { font-family:-apple-system,BlinkMacSystemFont,'Segoe UI',sans-serif; color:#1e293b; padding:32px; font-size:13px; }
  .header { display:flex; justify-content:space-between; align-items:flex-start; border-bottom:3px solid #0f766e; padding-bottom:16px; margin-bottom:20px; }
  .facility { font-size:20px; font-weight:800; color:#0f766e; }
  .soap-badge { background:#0f766e; color:#fff; font-size:11px; font-weight:700; letter-spacing:1px; padding:3px 10px; border-radius:12px; text-transform:uppercase; }
  .meta-grid { display:grid; grid-template-columns:1fr 1fr; gap:8px; background:#f8fafc; border-radius:8px; padding:14px 16px; margin-bottom:20px; border:1px solid #e2e8f0; }
  .meta-item .lbl { font-size:10px; font-weight:700; text-transform:uppercase; letter-spacing:.5px; color:#94a3b8; margin-bottom:2px; }
  .meta-item .val { font-size:13px; font-weight:600; color:#0f172a; }
  .section { margin-bottom:18px; }
  .section-label { font-size:10px; font-weight:700; text-transform:uppercase; letter-spacing:1px; color:#0f766e; margin-bottom:6px; padding-left:10px; border-left:3px solid #0f766e; }
  .section-body { font-size:13px; color:#1e293b; line-height:1.7; padding-left:13px; white-space:pre-wrap; }
  .footer { margin-top:32px; padding-top:12px; border-top:1px dashed #e2e8f0; text-align:center; font-size:11px; color:#94a3b8; }
  @media print { body { print-color-adjust:exact; } }
</style></head>
<body>
  <div class="header">
    <div>
      <div class="facility">🏥 ${facilityName}</div>
      <div style="font-size:12px;color:#64748b;margin-top:4px;">SOAP Consultation Note</div>
    </div>
    <span class="soap-badge">Confidential</span>
  </div>
  <div class="meta-grid">
    <div class="meta-item"><div class="lbl">Patient</div><div class="val">${patientName}</div></div>
    <div class="meta-item"><div class="lbl">Patient ID</div><div class="val">${patient?.patientId || '—'}</div></div>
    <div class="meta-item"><div class="lbl">Date</div><div class="val">${dateStr}</div></div>
    <div class="meta-item"><div class="lbl">Doctor</div><div class="val">${doctorName}</div></div>
  </div>
  ${sectionHtml}
  <div class="footer">
    <p>This document contains confidential medical information. Generated by AfyaScribe EMR.</p>
  </div>
</body>
</html>`;

  if (Platform.OS === 'web') {
    const w = window.open('', '_blank');
    w.document.write(html);
    w.document.close();
    w.print();
    return;
  }

  const { uri } = await Print.printToFileAsync({ html, base64: false });
  const canShare = await Sharing.isAvailableAsync();
  if (canShare) {
    await Sharing.shareAsync(uri, {
      mimeType: 'application/pdf',
      dialogTitle: 'SOAP Note',
      UTI: 'com.adobe.pdf',
    });
  } else {
    await Print.printAsync({ uri });
  }
}
